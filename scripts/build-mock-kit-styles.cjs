// Compile every original kit/theme/accent class ahead of time; no browser Tailwind runtime.
const fs = require('node:fs');
const path = require('node:path');
const { compile, optimize } = require('@tailwindcss/node');
const { harness } = require('../tests/helpers/harness.cjs');

async function main() {
  const { KITS, ACCENTS, KIT_SAMPLES, renderMock } = harness().load('web/lib/mock-kits.ts');
  const candidates = new Set();
  for (const kit of KITS) for (const accent of ACCENTS) for (const theme of ['light', 'dark']) {
    const sample = KIT_SAMPLES[kit];
    const items = ['good', 'warn', 'bad', 'neutral'].map((status, index) => ({ ...sample.items[index % sample.items.length], status }));
    const html = renderMock({ ...sample, items, kit, accent, theme });
    for (const match of html.matchAll(/class="([^"]*)"/g)) for (const token of match[1].split(/\s+/)) if (token) candidates.add(token);
  }
  const compiler = await compile('@import "tailwindcss";', { base: path.resolve(__dirname, '../web'), onDependency() {} });
  const css = optimize(compiler.build([...candidates]), { minify: true }).code.replace(/\/\*[\s\S]*?\*\//g, '');
  if (/<\/style|https?:|url\(/i.test(css)) throw new Error('Compiled kit CSS must have no external resources or HTML');
  fs.writeFileSync(path.resolve(__dirname, '../web/lib/mock-kit-styles.ts'), '// Generated by scripts/build-mock-kit-styles.cjs. Do not hand edit.\nexport const MOCK_KIT_CSS = ' + JSON.stringify(css) + ';\n');
  console.log(`Compiled ${candidates.size} kit utilities into ${css.length} bytes of static CSS.`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
